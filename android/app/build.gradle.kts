    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
}

val configuredBaseUrl = providers.gradleProperty("outboundOsBaseUrl")
    .orElse("https://app.outboundos.space/")
    .map { value -> if (value.endsWith('/')) value else "$value/" }

extensions.configure<ApplicationExtension> {
    namespace = "space.outboundos.android"
    // 37 does not exist in the SDK manager yet — the highest published platform
    // is 36, so the project as written could not build anywhere.
